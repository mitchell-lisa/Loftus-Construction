function fallbackAlt(key: string) {
  if (key.startsWith("st-peters-before")) return "St. Peters Road and the old wall before the work, May 2025";
  if (key.startsWith("brownsville")) return "Brownsville Road bridge over Neshaminy Creek";
  return "University Avenue Bridge over the Schuylkill River";
}

export function photo(key: string): Photo {
  const d = dims[key];
  if (!d) throw new Error(`Unknown photo ${key}`);
  return { src: `/images/work/${key}.jpg`, width: d[0], height: d[1], alt: alts[key] ?? fallbackAlt(key) };
}

